#!/usr/bin/env python3
"""Patch gateway+WebUI: durable run-scoped YOLO + deny-reason relay.

Problem (issue #136 / WebUI approval hardening):
  1. In gateway mode (webui_chat_backend=gateway) the AGENT and its approval
     state (tools.approval._session_yolo) run in the GATEWAY process. The
     WebUI's /api/session/yolo POST calls enable_session_yolo() on the WEBUI
     process's own copy, which never reaches the gateway — so the YOLO toggle
     appeared to work (frontend re-fetched its own flag) but never actually
     auto-approved anything at the enforcement boundary.
  2. The approval enforcement key in the gateway is the RUN ID
     (approval_session_key = run_id, set_current_session_key(run_id)), NOT
     the WebUI sid.  YOLO keyed by sid never reaches the enforcement boundary
     either — the toggle must be applied to the run's approval key.
  3. YOLO was in-memory only: a server/gateway restart silently dropped every
     session's auto-approve mode.
  4. A deny from the approval card/banner never carried a reason.

Fix (four files; same fail-loud / idempotent rules as patch-approval.py):
  1. api_server.py (gateway):
       * POST /v1/yolo {run_id?, session_id?, enabled} -> resolves the target
         run(s) (explicit run_id, or sid -> active run via _run_statuses /
         _run_approval_sessions) and enable_session_yolo(run_id) /
         disable_session_yolo(run_id) in the GATEWAY process — the key the
         approval boundary actually checks.
       * GET  /v1/yolo/{session_id} -> is_session_yolo_enabled() for the
         active run(s) of that sid (authoritative read for the WebUI).
       * _handle_run_approval: relay body.reason into
         resolve_gateway_approval(..., reason=...) so an explicit deny shows
         the user's reason to the agent.
  2. runner_client.py (webui): HttpRunnerClient.set_run_yolo(),
     get_run_yolo(), and respond_approval(..., reason=None).
  3. routes.py (webui): /api/session/yolo POST persists to a durable store
     (STATE_DIR/approval_mode.json, atomic) AND relays to the gateway
     endpoint for immediate enforcement; GET reads gateway-backed state. Plus
     reapply_persisted_yolo() so yolo re-applies on boot / gateway reconnect.
  4. server.py (webui): call reapply_persisted_yolo() once at boot so a
     restart re-applies any persisted run yolo to the gateway.

Rules (patch-approval.py pattern):
  - Fail LOUDLY (exit 1) when an anchor is absent or appears more than once
    (upgrade drift -> caught at build time, not silently skipped).
  - Idempotent: safe to run repeatedly on an already-patched file.

Usage:
  python3 patch-approval-yolo-durable.py \\
      /app/hermes-agent/gateway/platforms/api_server.py \\
      /app/hermes-webui/api/runner_client.py \\
      /app/hermes-webui/api/routes.py \\
      /app/hermes-webui/server.py
"""

