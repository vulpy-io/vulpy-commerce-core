def _apply_one(text: str, patch: dict, file_label: str) -> str:
    anchor = patch["anchor"]
    old = patch["old"]
    count = text.count(old)
    if count == 0:
        sys.stderr.write(
            f"ERROR: anchor not found in {file_label}:\n  anchor: {anchor!r}\n"
            f"  Hermes changed shape — update {__file__}\n"
        )
        sys.exit(1)
    if count > 1:
        sys.stderr.write(
            f"ERROR: anchor appears {count}x in {file_label}:\n  {old!r}\n"
            "  Refusing ambiguous patch.\n"
        )
        sys.exit(1)
    return text.replace(old, patch["new"], 1)


def _apply_all(patches, text, label):
    for p in patches:
        text = _apply_one(text, p, label)
    return text


